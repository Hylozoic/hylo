/**
 * Report of Redis sessions (`sess:*`) grouped by the user they belong to.
 *
 * Usage:
 *   REDIS_URL=... node scripts/report-session-counts.js [--top 25] [--user 83857] [--purge [--yes]]
 *   heroku run --app <backend-app> node scripts/report-session-counts.js --user 83857
 *
 * --purge lists logged-in sessions whose id is not `<their userId>:…` (pre-v7.1 logins, sessions
 * of deleted users). User.clearSessionsFor can't find these, so logging out everywhere, password
 * changes and account deletion miss them. Add --yes to delete them; those browsers must log in again.
 *
 * Session ids are `<userId>:<uuid>` when created by a login since v7, `anon:<uuid>` when
 * created anonymously (all sessions before v7), and a bare id when generated by sails sockets.
 * "Last active" is cookie.expires minus originalMaxAge, because express-session rolls the
 * stored expiry forward on every request.
 */
const Redis = require('ioredis')

const SCAN_COUNT = 1000
const DELETE_BATCH = 500
const MISMATCH_LIST_LIMIT = 20

/**
 * Entry point: scans every session, aggregates per user and prints the report.
 */
async function main () {
  const args = parseArgs(process.argv.slice(2))
  if (!process.env.REDIS_URL) {
    console.error('[report-session-counts] REDIS_URL is required')
    process.exit(1)
  }

  const redis = new Redis(process.env.REDIS_URL, { maxRetriesPerRequest: 3 })
  const stats = await collectStats(redis, args.user)

  printSummary(stats)
  printMismatches(stats)
  printSharedEmails(stats)
  printTopUsers(stats, args.top)
  if (args.user) printUserSessions(stats, args.user)
  if (args.purge) await purgeUnfindableSessions(redis, stats, args.yes)

  await redis.quit()
}

/**
 * Parses --top, --user, --purge and --yes flags.
 * @param {string[]} argv
 * @returns {{ top: number, user: string|null, purge: boolean, yes: boolean }}
 */
function parseArgs (argv) {
  const args = { top: 25, user: null, purge: false, yes: false }
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--top') args.top = parseInt(argv[++i], 10) || args.top
    else if (argv[i] === '--user') args.user = String(argv[++i])
    else if (argv[i] === '--purge') args.purge = true
    else if (argv[i] === '--yes') args.yes = true
  }
  return args
}

/**
 * Deletes (with --yes) or just counts logged-in sessions that User.clearSessionsFor can't find.
 * @param {Redis} redis
 * @param {object} stats
 * @param {boolean} confirmed
 */
async function purgeUnfindableSessions (redis, stats, confirmed) {
  const keys = stats.unfindable
  console.log()
  console.log(`== Logged in sessions not keyed by their user: ${keys.length} ==`)
  if (!confirmed) {
    console.log('dry run, nothing deleted. Re-run with --purge --yes to delete them.')
    return
  }

  let deleted = 0
  for (let i = 0; i < keys.length; i += DELETE_BATCH) {
    deleted += await redis.del(...keys.slice(i, i + DELETE_BATCH))
  }
  console.log(`deleted ${deleted} sessions`)
}

/**
 * Walks all `sess:*` keys with SCAN/MGET and builds the aggregate stats.
 * @param {Redis} redis
 * @param {string|null} detailUserId - collect per-session details for this user
 */
async function collectStats (redis, detailUserId) {
  const stats = {
    total: 0,
    unparseable: 0,
    withUser: 0,
    withoutUser: 0,
    byKeyType: { user: 0, anon: 0, bare: 0 },
    anonWithUser: 0,
    mismatches: [],
    mismatchCount: 0,
    noEmail: 0,
    emailUsers: new Map(),
    users: new Map(),
    detail: [],
    unfindable: []
  }

  let cursor = '0'
  do {
    const [nextCursor, keys] = await redis.scan(cursor, 'MATCH', 'sess:*', 'COUNT', SCAN_COUNT)
    cursor = nextCursor
    if (keys.length === 0) continue
    const values = await redis.mget(keys)
    keys.forEach((key, i) => addSession(stats, key, values[i], detailUserId))
  } while (cursor !== '0')

  return stats
}

/**
 * Folds one session into the stats.
 * @param {object} stats
 * @param {string} key - full redis key, e.g. `sess:anon:<uuid>`
 * @param {string|null} value - JSON session data
 * @param {string|null} detailUserId
 */
function addSession (stats, key, value, detailUserId) {
  if (value === null) return // expired between SCAN and MGET
  stats.total++

  let session
  try {
    session = JSON.parse(value)
  } catch (e) {
    stats.unparseable++
    return
  }

  const sid = key.slice('sess:'.length)
  const keyOwner = sid.includes(':') ? sid.split(':')[0] : null
  const keyType = keyOwner === null ? 'bare' : keyOwner === 'anon' ? 'anon' : 'user'
  stats.byKeyType[keyType]++

  const userId = session.userId ? String(session.userId) : null
  if (!userId) {
    stats.withoutUser++
    return
  }
  stats.withUser++
  if (keyType === 'anon') stats.anonWithUser++
  if (keyOwner !== userId) stats.unfindable.push(key)

  if (keyType === 'user' && keyOwner !== userId) {
    stats.mismatchCount++
    if (stats.mismatches.length < MISMATCH_LIST_LIMIT) {
      stats.mismatches.push({ sid: maskSid(sid), keyOwner, userId, lastActive: lastActiveAt(session) })
    }
  }

  if (session.userEmail) {
    const email = String(session.userEmail).toLowerCase()
    const sessions = stats.emailUsers.get(email) || []
    sessions.push({ sid: maskSid(sid), userId, keyType, lastActive: lastActiveAt(session) })
    stats.emailUsers.set(email, sessions)
  } else {
    stats.noEmail++
  }

  const lastActive = lastActiveAt(session)
  const user = stats.users.get(userId) || { count: 0, byKeyType: { user: 0, anon: 0, bare: 0 }, newest: null, oldest: null }
  user.count++
  user.byKeyType[keyType]++
  if (lastActive && (!user.newest || lastActive > user.newest)) user.newest = lastActive
  if (lastActive && (!user.oldest || lastActive < user.oldest)) user.oldest = lastActive
  stats.users.set(userId, user)

  if (detailUserId && (userId === detailUserId || keyOwner === detailUserId)) {
    stats.detail.push({
      sid: maskSid(sid),
      keyType,
      keyOwner,
      userId,
      lastActive,
      expires: session.cookie?.expires ? new Date(session.cookie.expires) : null,
      hasUserEmail: !!session.userEmail,
      otherFields: Object.keys(session).filter(k => !['cookie', 'userId', 'userEmail'].includes(k))
    })
  }
}

/**
 * Time of the last request on this session, derived from the rolling cookie expiry.
 * @param {object} session
 * @returns {Date|null}
 */
function lastActiveAt (session) {
  const { expires, originalMaxAge } = session.cookie || {}
  if (!expires || !originalMaxAge) return null
  return new Date(new Date(expires).getTime() - originalMaxAge)
}

/**
 * Keeps the key prefix and the first 8 characters of the id so the output can't be used as a cookie.
 * @param {string} sid
 */
function maskSid (sid) {
  const parts = sid.split(':')
  const id = parts.pop()
  return [...parts, id.slice(0, 8) + '…'].join(':')
}

/**
 * Formats a date as an ISO string without milliseconds.
 * @param {Date|null} date
 */
function fmt (date) {
  return date ? date.toISOString().replace(/\.\d+Z$/, 'Z') : '-'
}

/**
 * Prints overall totals.
 * @param {object} stats
 */
function printSummary (stats) {
  console.log('== Sessions ==')
  console.log(`total keys:                 ${stats.total}`)
  console.log(`  logged in (have userId):  ${stats.withUser}`)
  console.log(`  anonymous:                ${stats.withoutUser}`)
  console.log(`  unparseable:              ${stats.unparseable}`)
  console.log(`key types: <userId>:  ${stats.byKeyType.user}   anon:  ${stats.byKeyType.anon}   bare (socket-generated):  ${stats.byKeyType.bare}`)
  console.log(`anon: keys holding a userId (pre-v7 logins, or token/bearer/verifyEmail paths): ${stats.anonWithUser}`)
  console.log(`distinct users with sessions: ${stats.users.size}`)
  console.log()
}

/**
 * Prints sessions whose key says one user but whose data says another.
 * @param {object} stats
 */
function printMismatches (stats) {
  console.log(`== Key prefix does not match session userId: ${stats.mismatchCount} ==`)
  stats.mismatches.forEach(m => {
    console.log(`  ${m.sid}  key user ${m.keyOwner}  session user ${m.userId}  last active ${fmt(m.lastActive)}`)
  })
  if (stats.mismatchCount > stats.mismatches.length) {
    console.log(`  … and ${stats.mismatchCount - stats.mismatches.length} more`)
  }
  console.log()
}

/**
 * Prints emails found on sessions of more than one user. checkClientCredentials and
 * verifyEmail overwrite userId without touching userEmail, so a session moved to another
 * user that way keeps the previous user's email.
 * @param {object} stats
 */
function printSharedEmails (stats) {
  const shared = [...stats.emailUsers.entries()]
    .filter(([, sessions]) => new Set(sessions.map(s => s.userId)).size > 1)
  console.log(`== userEmail found on sessions of more than one user: ${shared.length} ==`)
  shared.forEach(([email, sessions]) => {
    console.log(`  ${maskEmail(email)}`)
    sessions
      .sort((a, b) => a.userId.localeCompare(b.userId) || (a.lastActive || 0) - (b.lastActive || 0))
      .forEach(s => console.log(`    user ${s.userId.padEnd(8)} ${s.sid.padEnd(16)} ${s.keyType.padEnd(5)} last active ${fmt(s.lastActive)}`))
  })
  console.log(`logged in sessions without userEmail (set by checkClientCredentials or verifyEmail): ${stats.noEmail}`)
  console.log()
}

/**
 * Keeps the first character of the local part and the domain.
 * @param {string} email
 */
function maskEmail (email) {
  const [local, domain] = email.split('@')
  return `${local.slice(0, 1)}***@${domain || ''}`
}

/**
 * Prints the users with the most sessions.
 * @param {object} stats
 * @param {number} top
 */
function printTopUsers (stats, top) {
  const rows = [...stats.users.entries()]
    .sort((a, b) => b[1].count - a[1].count)
    .slice(0, top)

  console.log(`== Top ${rows.length} users by session count ==`)
  console.log('userId      total  <userId>:  anon:  bare  oldest last active    newest last active')
  rows.forEach(([userId, u]) => {
    console.log([
      userId.padEnd(10),
      String(u.count).padStart(6),
      String(u.byKeyType.user).padStart(10),
      String(u.byKeyType.anon).padStart(6),
      String(u.byKeyType.bare).padStart(5),
      ' ' + fmt(u.oldest).padEnd(21),
      fmt(u.newest)
    ].join(' '))
  })
  console.log()
}

/**
 * Prints every session that belongs to (or is keyed to) one user.
 * @param {object} stats
 * @param {string} userId
 */
function printUserSessions (stats, userId) {
  const rows = stats.detail.sort((a, b) => (b.lastActive || 0) - (a.lastActive || 0))
  console.log(`== Sessions for user ${userId}: ${rows.length} ==`)
  rows.forEach(s => {
    const owner = s.userId === userId ? '' : `  (session user ${s.userId})`
    const extra = s.otherFields.length ? `  fields: ${s.otherFields.join(',')}` : ''
    console.log(`  ${s.sid.padEnd(16)} last active ${fmt(s.lastActive)}  expires ${fmt(s.expires)}  userEmail ${s.hasUserEmail ? 'yes' : 'no'}${owner}${extra}`)
  })
}

main().catch(err => {
  console.error('[report-session-counts]', err)
  process.exit(1)
})
